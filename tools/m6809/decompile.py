def build_functions(program, merged=True):
    """The functions lifted ({entry: Function}) and those that do not lift; with 'merged', the cycles of a block
    the IRQ cannot interrupt as one m6809_block (function.merge_time)"""
    builder = functions.Builder(program)
    built, failures = {}, []
    for entry in sorted(program.entries):
        try:
            built[entry] = builder.build(entry)
        except (lift.Unsupported, AssertionError) as problem:
            failures.append((entry, str(problem)))
    if merged and not failures:
        for entry in functions.masked_functions(program, built):
            functions.merge_time(built[entry])
    if USE_D:
        for function in built.values():
            functions.use_d(function)
    return built, failures


def check(program):
    built, failures = build_functions(program)
    for entry, function in built.items():
        try:
            stack.analyse(function)
        except stack.StackError as problem:
            failures.append((entry, str(problem)))
            continue
        left = stack.leftovers(function)
        if left:
            failures.append((entry, f"{len(left)} statements still use S, the first: {left[0]}"))
    ends = Counter(type(block.end).__name__ for function in built.values() for block in function.blocks.values())
    choices = sum(1 for function in built.values() for block in function.blocks.values()
                  for statement in block.statements + [block.end]
                  if isinstance(statement, (ir.Call, ir.Switch)) and statement.address is not None and any(
                      isinstance(node, ir.Op) and node.name == "helper:m6809_bank_code"
                      for node in ir.walk(statement.address)))
    exits = sum(1 for function in built.values() if getattr(function, "exits_caller", False))
    print(f"functions:  {len(built)} ({sum(len(body) for body in program.bodies.values())} instructions)")
    print(f"blocks:     {sum(ends.values())}")
    print("block ends: " + ", ".join(f"{kind} {count}" for kind, count in ends.most_common()))
    print(f"by bank:    {choices} calls or jumps into the window choose their bank by the latch")
    print(f"exits:      {exits} functions return for their caller too")
    print(f"problems:   {len(failures)}")
    for entry, problem in failures[:60]:
        print(f"  {functions.label(entry)}  {program.names.get(entry, '')}  {problem}")
    return 1 if failures else 0


def core_symbols():
    """symbols.txt's names in the core's format (disassemble.load_names), for the passes that name things: the work
    RAM's variables ("var" lines: type=u8 by default, count=N an array of N)"""
    os.makedirs(REPORTS, exist_ok=True)
    lines = ["# made by tools/m6809/decompile.py from symbols.txt: the names the core's passes read"]
    for symbol in sorted(SYMBOLS.entries, key=lambda s: s.address):
        if symbol.kind != "var":
            continue
        count = symbol.keys.get("count")
        name = symbol.name + (f"[{int(count, 0)}]" if count else "")
        lines.append(f"{symbol.address:04X} var {name} {symbol.keys.get('type', 'u8')}")
    # (the structures, their fields, where a register points at one: as they are; "below" lines are the driver's)
    lines += [line for line in SYMBOLS.core_lines if not line.startswith(("below ", "instance "))]
    with open(CORE_SYMBOLS, "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")
    return CORE_SYMBOLS


def open_entries(program, built):
    """The functions nothing calls, jumps to or dispatches to (the vectors' are called by the board)"""
    reached = set(program.vectors)
    for function in built.values():
        for block in function.blocks.values():
            for statement in block.statements + [block.end]:
                if isinstance(statement, ir.Call):
                    reached |= {statement.target} if statement.target is not None else set(statement.choices)
                elif isinstance(statement, ir.TailCall):
                    reached.add(statement.target)
                elif isinstance(statement, ir.Switch):
                    reached |= {target[1] for target in statement.cases.values()
                                if isinstance(target, tuple) and target[0] == "tail"}
    return {entry for entry in built if entry not in reached}


