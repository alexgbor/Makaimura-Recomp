def replaced(node, pattern, replacement):
    """'node' with each occurrence of 'pattern' replaced (top down)"""
    if node == pattern:
        return replacement
    if isinstance(node, ir.Load):
        address = replaced(node.address, pattern, replacement)
        return node if address is node.address else ir.Load(address, node.bits)
    if isinstance(node, ir.Op):
        args = tuple(replaced(arg, pattern, replacement) for arg in node.args)
        return node if all(new is old for new, old in zip(args, node.args)) else ir.Op(node.name, args, node.bits)
    return node


def held_parts(index, value):
    """(value, what reads it from the register) for what register 'index' holds once set to 'value': the whole of
    it, and for D the byte A or B a write of one byte left in it (or(and(D, FF00), zext(b)): B; the same with 00FF
    and shl(zext(a), 8): A)"""
    bits = cpu.current.register_bits[index]
    register = ir.Reg(index, bits)
    parts = [(value, register)]
    if isinstance(value, ir.Op) and value.name == "or" and bits == 16:
        mask, part = value.args
        if isinstance(mask, ir.Op) and mask.name == "and" and mask.args[0] == register \
                and isinstance(mask.args[1], ir.Const):
            if mask.args[1].value == 0xFF00 and isinstance(part, ir.Op) and part.name == "zext" \
                    and part.args[0].bits == 8:
                parts.append((part.args[0], ir.trunc(register, 8)))
            elif mask.args[1].value == 0x00FF and isinstance(part, ir.Op) and part.name == "shl" \
                    and part.args[1] == ir.Const(8, 8) and isinstance(part.args[0], ir.Op) \
                    and part.args[0].name == "zext" and part.args[0].args[0].bits == 8:
                parts.append((part.args[0].args[0], ir.trunc(ir.op("shr", (register, ir.Const(8, 8)), 16), 8)))
    return parts


def kept_flags(block, flow):
    """conditions.carried (the flags a block leaves set, as expressions that hold at its end), where a flag about to
    go stale is first written with what a register holds: a value the flag's expression computes that is still in a
    register the statement does not write (LDA <$80 / BMI: A's sign, not the RAM's, past an IRQ that may change
    it), or that the statement itself puts in a register (DECB / BNE: t = b - 1, zero = t == 0, b = t: b == 0). Both
    are values of the same moment, before the statement; the register holds it after"""
    values, flags, held = {}, {}, {}      # held: register -> [(value, how to read it)], while they hold
    for statement in block.statements:
        if isinstance(statement, ir.SetTemp):
            resolved = conditions.resolve_all(statement.value, values)
            if resolved is not None and not cleanup.has_effect(resolved):
                values[statement.temp.name] = resolved
            continue
        written, writes_memory = conditions.written_by(statement, flow)
        resolved = conditions.resolve_all(statement.value, values) if isinstance(statement, ir.SetReg) else None

        def stale(expression):
            reads, memory = conditions.reads_of(expression)
            return bool(reads & written) or (memory and writes_memory)
        for name in list(flags):
            if ("f", name) in written:
                del flags[name]
                continue
            if not stale(flags[name]):
                continue
            expression = flags[name]
            candidates = [part for register, parts in held.items() if ("r", register) not in written for part in parts]
            if resolved is not None and not cleanup.has_effect(resolved):
                candidates += held_parts(statement.index, resolved)
            readers = {}
            for value, reader in candidates:
                if isinstance(value, ir.Const):
                    continue
                marker = ir.Temp(f"held{len(readers)}", value.bits)
                before = expression
                expression = replaced(expression, value, marker)
                if expression is not before:
                    readers[marker] = reader
            # (with the values marked: what is left must not be stale; then the registers read in their place)
            if stale(expression):
                del flags[name]
                continue
            for marker, reader in readers.items():
                expression = replaced(expression, marker, reader)
            flags[name] = expression
        for register in list(held):
            held[register] = [(value, reader) for value, reader in held[register] if not stale(value)]
            if ("r", register) in written or not held[register]:
                del held[register]
        for table in (values,):
            for name in list(table):
                if stale(table[name]):
                    del table[name]
        if isinstance(statement, ir.SetFlag):
            value = conditions.resolve_all(statement.value, values)
            if value is not None and ("f", statement.name) not in conditions.reads_of(value)[0]:
                flags[statement.name] = value
        elif resolved is not None and not cleanup.has_effect(resolved) \
                and ("r", statement.index) not in conditions.reads_of(resolved)[0]:
            held[statement.index] = held_parts(statement.index, resolved)
        elif resolved is not None and not cleanup.has_effect(resolved):
            held[statement.index] = [part for part in held_parts(statement.index, resolved)[1:]
                                     if ("r", statement.index) not in conditions.reads_of(part[0])[0]]
    return flags


def recover_kept(function, flow, masked=False):
    """The branches on flags their own block set from registers (CMPA #4: A - 4, A read where the flags are set),
    which conditions.recover leaves on flags (it compares registers only where it checked that nothing changes them
    before the branch: the block before's flags, conditions.carried). The same check on the block itself: the flags
    it leaves set as expressions that still hold at its end (what they read not written after, no memory read past a
    write or an m6809_block, where the IRQ may change the work RAM; the registers are the C's own, which the IRQ does
    not touch). In a function only the masked code runs ('masked': function.masked_functions) the time's effects
    write nothing the program reads (no IRQ comes in; a device's read is never carried, cleanup.has_effect), so a
    value read from the work RAM holds past them too. How many changed"""
    changed = 0
    for block in function.blocks.values():
        end = block.end
        if not isinstance(end, ir.Branch):
            continue
        name = conditions.condition_name(end.condition)
        if name is None or not any(isinstance(node, ir.Flag) for node in ir.walk(end.condition)):
            continue
        view = block
        if masked:
            view = SimpleNamespace(statements=[statement for statement in block.statements if not (
                isinstance(statement, ir.Effect) and statement.name in ("m6809_block", "m6809_cycles", "m6809_at"))])
        flags = kept_flags(view, flow)
        if not conditions.FLAGS_READ[name] <= set(flags):
            continue
        new = conditions.rewrite_condition(end.condition, flags, {}, checked=True)
        if new is not end.condition:
            end.condition = new
            changed += 1
    return changed


def analyse(program, built):
    """Stack slots, preserved registers and the data flow summaries, in place"""
    for function in built.values():
        stack.analyse(function)
    flow = dataflow.Program(built, analysis_view(program), [program.irq], signatures.CONTEXT)
    signatures.OPEN = open_entries(program, built)
    flow.declared = {}
    flow.solve()
    while sum(len(preserved.analyse(function, flow.call_writes, context=signatures.CONTEXT))
              for function in built.values()):
        flow.solve()
    changed = sum(conditions.recover(function, flow) for function in built.values())
    masked = functions.masked_functions(program, built)
    changed += sum(recover_kept(function, flow, entry in masked) for entry, function in built.items())
    if changed:
        flow.reset()
        flow.solve()
    flow.conditions_recovered = changed
    return flow


def write_c(program, out_dir):
    built, failures = build_functions(program)
    if failures:
        raise SystemExit(f"{len(failures)} functions do not lift, the first: {functions.label(failures[0][0])} "
                         f"{failures[0][1]}")
    flow = analyse(program, built)
    found = signatures.compute(flow)
    names = dict(program.names)
    for entry, function_name in names.items():
        if not IDENTIFIER.match(function_name):
            raise SystemExit(f"{functions.label(entry)}: '{function_name}' cannot be a C function name")
    if USE_D:
        pairs.PAIRS = {functions.D: (lift.A, lift.B)}
        pairs.BYTES = {lift.A: "a", lift.B: "b"}
        for entry, function in built.items():
            pairs.split(function, flow, found[entry])
    before = sum(len(block.statements) for function in built.values() for block in function.blocks.values())
    arguments = {}
    for entry, signature in found.items():
        registers = {value[1] for value in signature.params - signature.results if value[0] == "r"}
        returned = next(iter(signature.results)) if len(signature.results) == 1 else None
        if returned is not None and returned[0] == "r" and returned in signature.params:
            registers.add(returned[1])
        arguments[entry] = registers
    whole = set()
    live_after, live_at_start = {}, {}
    for entry, function in built.items():
        expressions.drop_repacks(function, flow)
        after, start = cleanup.eliminate(flow, function, found[entry].results, signatures.CONTEXT, arguments)
        expressions.tidy(function, flow, after, whole)
        results_of_calls = call_results(function, found, flow)
        if expressions.propagate_constants(function, results_of_calls, signatures.CONTEXT) \
                | expressions.fold_kept_constants(function, results_of_calls, signatures.CONTEXT):
            after, start = cleanup.eliminate(flow, function, found[entry].results, signatures.CONTEXT, arguments)
            expressions.tidy(function, flow, after, whole)
        if expressions.inline_registers(function, flow, after, whole):
            expressions.simplify_function(function)
        if expressions.switch_values(function, flow):
            after, start = cleanup.eliminate(flow, function, found[entry].results, signatures.CONTEXT, arguments)
            expressions.tidy(function, flow, after, whole)
        knownbits.simplify(function, found[entry], signatures.CONTEXT, results_of_calls)
        expressions.simplify_function(function)
        if USE_D:
            pairs.tidy_bytes(function, after)
        live_after[entry] = after
        live_at_start[entry] = start

    SYMBOLS.entries = program.syms.entries
    SYMBOLS.core_lines = program.syms.core_lines
    symbols_path = core_symbols()
    known = core_disassemble.load_names(symbols_path, REGISTERS)
    emit.use_memory_map(known)
    # a structure right below where the code's pointer to another points ("below STRUCT SIZE UNDER": the objects' first
    # 0x10 bytes, which their handlers reach at negative offsets from X)
    for line in program.syms.core_lines:
        words = line.split()
        if words[0] == "below":
            pointers.BELOW[words[1]] = (int(words[2], 16), words[3])
        if words[0] == "instance":
            # "instance ADDRESS STRUCT NAME": a structure at a fixed address (the player's record), its fields by
            # name where the code reaches them by their own address, the address by NAME
            address = int(words[1], 16)
            pointers.INSTANCES[address] = (words[2], known.structs[words[2]])
            INSTANCE_NAMES[(words[2].upper(), address)] = words[3]
    # what symbols.txt's param and local lines say a register points at (as the 68000's driver takes them)
    entries_by_name = {name: entry for entry, name in names.items()}
    hints, site_hints = {}, {}
    for (function_name, register), struct in known.param_structs.items():
        if function_name in entries_by_name:
            hints.setdefault(entries_by_name[function_name], {})[register] = pointers.link_kind(struct)
    for (function_name, spot, value), struct in known.local_structs.items():
        if not value.startswith("r"):
            continue
        if spot == "entry" and function_name in entries_by_name:
            hints.setdefault(entries_by_name[function_name], {})[int(value[1:])] = pointers.link_kind(struct)
        elif spot != "entry":
            site_hints[(spot, int(value[1:]))] = pointers.link_kind(struct)
    typing = pointers.Program(built, flow, found,
                              {entry: call_results(function, found, flow) for entry, function in built.items()},
                              signatures.CONTEXT, known.targets, hints, site_hints)
    fields, accesses = typing.run()
    through = [(hit[1], hit[2]) for found_fields in fields.values() for hit in found_fields.values()
               if hit[0] == "global"]
    data_names = {s.address: s.name for s in program.syms.entries if s.kind == "data" and s.bank is None}
    named = memory.Memory(known, memory.accesses_of(built.values()) + through, data_names)
    always = {entry: set(summary.always) for entry, summary in flow.summaries.items()}
    rom_byte = program.rom.reader(None)
    emitter = emit.Emitter(built, found, names, named, always, pointers.Layouts(accesses, known),
                           lambda address: rom_byte(address) << 8 | rom_byte(address + 1))
    emitter.writes = {entry: set(summary.writes) for entry, summary in flow.summaries.items()}
    emitter.flow = flow
    emitter.data_labels = {address: name for address, name in data_names.items() if address not in named.tables}
    emitter.code_labels = {s.address: s.name for s in program.syms.entries if s.kind == "code" and s.bank is None}
    emitter.param_pointers = {entry: set(kinds) for entry, kinds in hints.items()}
    emitter.local_sites = {(spot, value): name for (_, spot, value), name in known.locals.items() if spot != "entry"}
    joined = {}
    for entry, function in built.items():
        notes = (live_after[entry], fields[entry])
        if emitter.by_pointer(entry):
            joined[entry] = []
            for tail_calls, meet in ((False, False), (True, False), (False, True), (True, True)):
                way = twin(function, notes)
                structure.join_exits(way, notes, tail_calls)
                way.meet_at_exit = meet
                structure.split_loop_entries(way, notes)
                joined[entry].append(way)
        structure.split_loop_entries(function, notes)

    def writer_of(entry, function=None):
        return emit.Writer(emitter, function or built[entry], live_after[entry], fields[entry], live_at_start[entry])
    writers = {entry: writer_of(entry) for entry in built}
    texts, problems = {}, []
    for entry, writer in writers.items():
        try:
            texts[entry] = writer.write()
        except (decompiler_emit.EmitError, GotoError) as problem:
            problems.append((entry, str(problem)))
    emitter.shared_results = decompiler_emit.shared_results(texts.values())
    for entry in texts:
        if emitter.shared_results.get(emitter.names.get(entry)):
            texts[entry] = writers[entry].write()
    for entry in joined:
        for way in joined[entry] if entry in texts else ():
            other = writer_of(entry, way)
            try:
                text = other.write()
            except (decompiler_emit.EmitError, GotoError):
                continue
            if fewer_write_backs(text, texts[entry]):
                writers[entry], texts[entry] = other, text
    split = fewer_controls(texts, writers, lambda entry, way: writer_of(entry, way),
                           lambda entry: (live_after[entry], fields[entry]))
    emitter.shared_results = decompiler_emit.shared_results(texts.values())
    for entry in set(joined) | split:
        if entry in texts and emitter.shared_results.get(emitter.names.get(entry)):
            texts[entry] = writers[entry].write()
    if problems:
        for entry, problem in problems[:30]:
            print(f"  {functions.label(entry)}  {problem}")
        raise SystemExit(f"{len(problems)} functions could not be written")

    variables = {s.name: s.address for s in program.syms.entries if s.kind == "var"}
    place = word_places(variables, {(struct.upper(), name): offset
                                    for (struct, offset), (name, _) in known.fields.items()})
    texts = {entry: join_bus_words(join_words(text, place)) for entry, text in texts.items()}
    # (a structure at its fixed address by the name symbols.txt's instance line gives it: OBJECT(PLAYER)->x; only
    # there, a number of that value elsewhere being no address: queue_task(0x500) is task 5)
    for (macro, address), name in INSTANCE_NAMES.items():
        pattern = re.compile(rf"\b{macro}\(0x0*{address:X}u\)")
        texts = {entry: pattern.sub(f"{macro}({name})", text) for entry, text in texts.items()}
    texts = {entry: side_timing(text) for entry, text in texts.items()}
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    entries = sorted(built)
    files = source_files(symbols_path, entries, lambda entry: entry, "game_{number:02}",
                         "the game's functions, part {number:02} (in the order of their addresses)")
    prototypes = grouped_prototypes(files, emitter.prototype)
    (out / "game.h").write_text(
        HEADER + "#ifndef MAKAIMURA_GAME_H\n#define MAKAIMURA_GAME_H\n\n#include \"m6809/program.h\"\n"
        "#include \"ram.h\"\n\n" + "\n".join(prototypes) + "\n\n#endif\n", encoding="ascii")
    (out / "ram.h").write_text(
        HEADER + "#ifndef MAKAIMURA_RAM_H\n#define MAKAIMURA_RAM_H\n\n" + "\n".join(named.declarations())
        + "\n\n/* data in the program ROM symbols.txt names */\n"
        + "\n".join(f"#define {name}_ADDRESS 0x{address:04X}u" for address, name in sorted(emitter.data_labels.items()))
        + "\n\n/* the structures at fixed addresses (symbols.txt's instance lines) */\n"
        + "\n".join(f"#define {name} 0x{address:04X}u" for (_, address), name in sorted(INSTANCE_NAMES.items()))
        + "\n\n/* the game's structures in work RAM */\n"
        + "\n".join(emitter.layouts.declarations())
        + "\n\n#endif\n", encoding="ascii")
    write_sources(out, files, texts, "game.h", header=lambda name, description: HEADER + f"/* {description} */\n")
    write_signatures(out / "functions.txt", entries, emitter, typing.entry_kinds)
    reset, irq = program.reset, program.irq
    for vector in (reset, irq):
        if emitter.wrapper(vector) is not None:
            raise SystemExit(f"the code at {functions.label(vector)} takes parameters")
    # where a state goes on: the function the main loop waits for work in, from its start, with U
    idle = [entry for entry in program.idle if entry in built]
    if len(idle) != 1 or emitter.prototype(idle[0]) != f"void {names[idle[0]]}(uint16_t u)":
        raise SystemExit("symbols.txt's idle: one function, the main loop's, which takes U and nothing else")
    (out / "vectors.c").write_text(
        HEADER + "#include \"game.h\"\n\n/* the code at the reset vector and at the IRQ's, as the runtime calls them */\n"
        f"void program_reset(void)\n{{\n\t{names[reset]}();\n}}\n\nvoid program_irq(void)\n{{\n\t{names[irq]}();\n}}\n\n"
        "/* a state's way on: the main loop waiting for work (symbols.txt's idle), U what it keeps */\n"
        f"const uint16_t program_idle_address = 0x{idle[0]:04X}u;\n\n"
        f"void program_resume(uint16_t u)\n{{\n\t{names[idle[0]]}(u);\n}}\n",
        encoding="ascii")
    left = sum(len(block.statements) for function in built.values() for block in function.blocks.values())
    gotos = sum(text.count("goto ") for text in texts.values())
    print(f"functions:  {len(entries)} in {out}")
    print(f"statements: {left} ({before - left} dead ones removed)")
    print(f"branches:   {flow.conditions_recovered} now compare values instead of flags")
    print(f"gotos:      {gotos}, in {sum(1 for text in texts.values() if 'goto ' in text)} functions")
    return 0



def write_signatures(path, entries, emitter, entry_kinds):
    """What each function takes and hands back, by register, in its prototype's order, for the check of each
    function against MAME's core (tools/m6809/check_functions.py): "ADDRESS NAME RETURNED IN OUT [FLAGS]", RETURNED
    the register it returns (- for none), IN and OUT "register:bits,..." (- for none: OUT what it hands back
    through pointers), FLAGS entry_point and return_address where the prototype takes them. Registers by the core's
    names (a, b, d, x, y, u, dp, s; carry, zero, negative, overflow, half_carry, firq_mask, entire). Then what every
    caller agrees a register points at as the function starts (pointers.Program's entry_kinds), which the C may take
    as given: "register=global:ADDRESS" (that address: the C reads its fields as variables), "register=STRUCT:OFFSET"
    (into a structure of the work RAM)."""
    def width(entry, value, pointer):
        if value[0] != "r":
            return 32
        if pointer:
            return decompiler_emit.register_bits(value[1])
        return emitter.param_widths.get(entry, {}).get(value[1], decompiler_emit.register_bits(value[1]))

    lines = []
    for entry in entries:
        returned = emitter.returned(entry)
        returned_text = "-" if returned is None else \
            f"{decompiler_emit.value_name(returned)}:" + str(
                emitter.result_bits.get(entry, decompiler_emit.register_bits(returned[1])) if returned[0] == "r" else 32)
        taken = ",".join(f"{decompiler_emit.value_name(value)}:{width(entry, value, False)}"
                         for value in emitter.by_value(entry)) or "-"
        given = ",".join(f"{decompiler_emit.value_name(value)}:{width(entry, value, True)}"
                         for value in emitter.by_pointer(entry)) or "-"
        flags = [flag for flag, present in (("entry_point", emitter.second_entries.get(entry)),
                                             ("return_address", entry in emitter.needs_return_address)) if present]
        kinds = []
        for index, kind in sorted(entry_kinds.get(entry, {}).items()):
            if not isinstance(index, int) or not isinstance(kind, tuple) or len(kind) < 2:
                continue
            register = decompiler_emit.register_name(index)
            if kind[0] == "global" and isinstance(kind[1], int):
                kinds.append(f"{register}=global:{kind[1]:X}")
            elif isinstance(kind[0], str) and isinstance(kind[1], int) and kind[0] not in ("unknown", "conflict"):
                kinds.append(f"{register}={kind[0]}:{kind[1]:X}")
        lines.append(" ".join([f"{entry:04X}", emitter.names[entry], returned_text, taken, given, *flags, *kinds]))
    path.write_text("\n".join(lines) + "\n", encoding="ascii")


# ---- the work RAM's 16-bit values ----

# (a byte the C names: unk_XXXX, a variable, an element of one, a field of a structure, NAME(pointer)->field)
LVALUE = r"(?:[A-Z_]+\((?:[^()]|\([^()]*\))*\)->\w+|unk_[0-9A-F]{4}|[A-Za-z_]\w*\[\d+\]|[A-Za-z_]\w*)"
READ = re.compile(r"\(\(uint32_t\)(" + LVALUE + r") << 8\) \| (" + LVALUE + r")")
WRITE = re.compile(r"^(\s*)(" + LVALUE + r") = (\w+) >> 8;\n\1(" + LVALUE + r") = (?:\(uint8_t\))?\3;$", re.M)


# two reads of the bus at one address and the next, the high byte first: ((uint32_t)ROM8(e) << 8) | mem_read8(e + 1)
BUS_BYTE = r"(?:ROM8|mem_read8)\(((?:[^()]|\((?:[^()]|\([^()]*\))*\))*)\)"
BUS_READ = re.compile(r"\(\(uint32_t\)" + BUS_BYTE + r" << 8\) \| " + BUS_BYTE)
BUS_PLACE = re.compile(r"^(?:\(uint16_t\)\()?(\w+)(?: ([+-]) (0x[0-9A-F]+|\d+)u)?\)?$")


TIME_AFTER = re.compile(r"\t+(m6809_block\(\d+\)|m6809_cycles\(.*\));\Z")
TIME_BEFORE = re.compile(r"\t+m6809_at\(\d+\);\Z")


def side_timing(text):
    """The board's time beside the statements it belongs to, a quarter of the lines on their own otherwise (the code
    the IRQ may interrupt keeps an m6809_block after each instruction): an instruction's cycles after it, on its line
    (a = temp_E4;  m6809_block(3);); an access's time before it, on its line (m6809_at(12); mem_write8(...)). The
    same statements in the same order: only the lines change"""
    lines = text.split("\n")
    out = []
    index = 0
    while index < len(lines):
        line = lines[index]
        previous = out[-1] if out else ""
        following = lines[index + 1] if index + 1 < len(lines) else ""
        indent = line[:len(line) - len(line.lstrip())]
        if TIME_AFTER.match(line) and previous.strip().endswith(";") \
                and not previous.lstrip().startswith(("//", "/*", "case ", "default")):
            out[-1] += "\t" + line.strip()
        elif TIME_BEFORE.match(line) and following.strip().endswith(";") and following.startswith(indent) \
                and not following[len(indent):].startswith(("\t", " ")) and not TIME_BEFORE.match(following):
            lines[index + 1] = indent + line.strip() + " " + following.strip()
        else:
            out.append(line)
        index += 1
    return "\n".join(out)


def bus_place(text):
    """(name, offset) of an address the C writes NAME, NAME + N or NAME - N (with a uint16_t cast), or None"""
    match = BUS_PLACE.match(text)
    if match is None or (text.startswith("(uint16_t)(") != (match.group(2) is not None)):
        return None
    offset = int(match.group(3), 0) if match.group(3) else 0
    return match.group(1), -offset if match.group(2) == "-" else offset


def join_bus_words(text):
    """The program's 16-bit reads through the bus (a table's entry, a pointer's word) as read16_bus(address): its two
    reads, high byte then low, in that order (C leaves the order of the two in one expression open)"""
    def change(match):
        start, end = match.span()
        before = text[:start].rstrip()
        after = text[end:].lstrip()
        if not (before.endswith(("(", "=", ",", "return", "|", "+")) and not before.endswith(("||", "==", "!=", "<=", ">=", "++"))
                and after[:1] in (")", ";", ",", "|", "+") and not after.startswith(("||", "++"))):
            return match.group(0)
        high, low = bus_place(match.group(1)), bus_place(match.group(2))
        if high is None or low is None or high[0] != low[0] or low[1] != high[1] + 1:
            return match.group(0)
        return f"read16_bus({match.group(1)})"
    return BUS_READ.sub(change, text)


def word_places(variables, fields=None):
    """The place of a work RAM byte by its C text: unk_XXXX and symbols.txt's variables (NAME, NAME[i]) their
    address; a structure's field (NAME(pointer)->field) its pointer's text and the field's offset ('fields': {(struct
    macro, field): offset})"""
    def place(text):
        if "->" in text:
            base, _, field = text.rpartition("->")
            offset = (fields or {}).get((base.split("(", 1)[0], field))
            return None if offset is None else (base, offset)
        if text.startswith("unk_"):
            return int(text[4:], 16)
        name, _, index = text.partition("[")
        if name not in variables:
            return None
        return variables[name] + (int(index[:-1]) if index else 0)
    return place


def join_words(text, place):
    """The 6809's 16-bit values in the work RAM (its high byte first) as read16(&high) and write16(&high, value)
    where the C reads or writes the two bytes of one: ((uint32_t)high << 8) | low, and high = v >> 8 then low = v.
    The same bytes read and written, in the same order: the work RAM has no time to keep (m6809/program.h)"""
    def consecutive(high, low):
        a, b = place(high), place(low)
        if isinstance(a, tuple) or isinstance(b, tuple):
            # (two fields of one structure, through the same pointer, one after the other)
            return isinstance(a, tuple) and isinstance(b, tuple) and a[0] == b[0] and b[1] == a[1] + 1
        return a is not None and b == a + 1 and b < 0x1E00

    def read(match):
        start, end = match.span()
        before = text[:start].rstrip()
        after = text[end:].lstrip()
        if not (before.endswith(("(", "=", ",", "return", "|")) and not before.endswith(("||", "==", "!=", "<=", ">="))
                and after[:1] in (")", ";", ",", "|") and not after.startswith("||")):
            return match.group(0)
        if not consecutive(match.group(1), match.group(2)):
            return match.group(0)
        return f"read16(&{match.group(1)})"

    def write(match):
        indent, high, value, low = match.groups()
        if not consecutive(high, low):
            return match.group(0)
        return f"{indent}write16(&{high}, {value});"
    previous = None
    while previous != text:
        previous = text
        text = READ.sub(read, text)
    text = WRITE.sub(write, text)
    # (read16(&x)) as an operand: the parentheses the pair needed; &name[0]: name
    text = re.sub(r"(?<![\w)\]])\((read16\(&" + LVALUE + r"\))\)", r"\1", text)
    return re.sub(r"&([A-Za-z_]\w*)\[0\]", r"\1", text)


