"""
Name:        decompile.py
Description: the 6809 program through the core's decompiler (tools/core/decompiler): readable C, no CPU left in it
             (milestone M6, in progress)
Version:     0.1.0
Created:     20-11-2026

license:BSD-3-Clause
    python tools/m6809/decompile.py [--check] [--out DIR] [--plain] [--rom PATH ...]

Writes src/ (git-ignored): game.h (the functions' prototypes), ram.h (the variables, tables and the board's places
by name), game_NN.c (the functions) and vectors.c (the reset's and the IRQ's code, as the runtime calls them).
--check builds every function (tools/m6809/function.py), follows its stack (decompiler/stack.py), and reports what
does not lift and what still uses S. Nothing it writes may be redistributed: it is the game's code, from the user's
own ROM.

The decompiler's passes take the 6809 by its profile (M6809 below): A, B and DP of 8 bits, X, Y and U of 16 (the
indexes of tools/m6809/lift.py), S the stack pointer, CC's flags but I (the runtime's mask: function.py), a call
pushing a 2-byte return address, big endian; the runtime takes the IRQ in "m6809_block" (an interrupt effect).
The steps after the lift are the core's sound program's (tools/core/decompile_sound.py): the stack's slots, the data
flow and what each function takes and hands back, the dead code and the expressions, the types of pointers, the
structure (no goto where it can) and the writer.
"""
