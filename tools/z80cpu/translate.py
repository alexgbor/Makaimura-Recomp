"""
Name:        translate.py
Description: the sound program translated into C an instruction at a time, timed as MAME 0.289's Z80 core times it:
             the sound side of the translation scaffold (milestone M5), run by the runtime's Z80 (runtime/src/z80.c)
Version:     0.1.0
Created:     19-11-2026

license:BSD-3-Clause
    python tools/z80cpu/translate.py [--rom PATH ...]

Writes build/generated/sound/: sound_program.h, sound_NN.c and sound_entries.c, never committed (the game's code,
translated from the user's own ROM).

As tools/m6809/translate.py does for the 6809: every instruction the static analysis finds (tools/z80cpu/analysis.py)
becomes the C of its IR (tools/z80cpu/lift.py), its time (z80.cycles, Z80 cycles from power-on) set before each
data access to that access's start (where MAME's core makes it) and to the instruction's end after it. Regions
are entered at any instruction and give back the address execution goes on at; the runtime's trampoline
dispatches it. After each instruction Z80_CHECK(next) lets the runtime stop the Z80 where its run ends (it runs
up to the time the 6809 needs it at) and take the IRQ: the IRQ's entry pushes the PC and gives back 0038.
"""
import argparse
import os
import sys
from collections import deque

TOOLS = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(TOOLS)
sys.path.insert(0, TOOLS)

from z80cpu import analysis, lift           # noqa: E402
from z80cpu.lift import ir                   # noqa: E402
from z80 import disassembler as zd           # noqa: E402
from v60 import emit_c                       # noqa: E402

OUT = os.path.join(ROOT, "build", "generated", "sound")
REGIONS_PER_FILE = 80
HEADER = """/*
 * Generated by tools/z80cpu/translate.py from the user's own ROM. Do not redistribute.
 * Makaimura (makaimurg): the Z80 sound program translated to C.
 */
"""
REGISTER_NAMES = ("z80.bc", "z80.de", "z80.hl", "z80.ix", "z80.iy", "z80.sp", "z80.a",
                  "z80.bc2", "z80.de2", "z80.hl2", "z80.a2")


class Names(emit_c.Names):
    def register(self, index):
        return REGISTER_NAMES[index]

    def flag(self, name):
        return "z80.f_" + name


class Printer(emit_c.Printer):
    def __init__(self):
        super().__init__(Names())

    def expr(self, node):
        if isinstance(node, ir.Load):
            return f"z80_read8({self.expr(node.address)})"
        return super().expr(node)

    def statement(self, node):
        if isinstance(node, ir.Store):
            return f"z80_write8({self.expr(node.address)}, (uint8_t)({self.expr(node.value)}));"
        return super().statement(node)

    def effect(self, node):
        if node.name == "di":
            return "z80_di();"
        if node.name == "ei":
            return "z80_ei();"
        if node.name == "im":
            return f"z80.im = {self.expr(node.args[0])};"
        raise ValueError(node.name)


def hex16(value):
    return f"0x{value & 0xFFFF:04X}u"


class Translator:
    def __init__(self, program, code):
        self.program = program
        self.code = code
        self.instructions = code.instructions
        self.lifted, self.unsupported = {}, {}
        for address, instruction in self.instructions.items():
            try:
                self.lifted[address] = lift.lift(instruction, program.read, prefix="t_")
            except lift.Unsupported as problem:
                self.unsupported[address] = str(problem)
        self.split()

    def local_successors(self, address):
        instruction = self.instructions[address]
        lifter = self.lifted.get(address)
        result = []
        if lifter is None:
            return result
        kind = lifter.control.kind
        if kind in ("next", "branch", "call", "call_if", "return_if", "halt"):
            result.append(lifter.next_address)
        if kind in ("goto", "branch"):
            result.append(lifter.control.target)
        return [a for a in result if a in self.instructions]

    def split(self):
        self.owner, self.regions = {}, {}
        starts = sorted(analysis.ENTRIES) + sorted(self.code.calls) + sorted(self.instructions)
        for start in starts:
            if start in self.owner or start not in self.instructions:
                continue
            body, work = [], deque([start])
            while work:
                address = work.popleft()
                if address in self.owner:
                    continue
                self.owner[address] = start
                body.append(address)
                work.extend(a for a in self.local_successors(address) if a not in self.owner)
            self.regions[start] = sorted(body)

    def transfer(self, region, address):
        if address in self.instructions and self.owner.get(address) == region:
            return f"goto L_{address:04X};"
        return f"return {hex16(address)};"

    def timed(self, statements, accesses, printer, counted):
        """the statements' C, the time set before each data access to its start; the cycles counted so far after"""
        lines = []
        data = [a for a in accesses if a.address is None]
        position = 0
        for statement in statements:
            is_access = isinstance(statement, ir.Store) or (isinstance(statement, ir.SetTemp) and
                                                          isinstance(statement.value, ir.Load))
            if is_access:
                at = data[position].cycle
                position += 1
                if at > counted:
                    lines.append(f"z80.cycles += {at - counted};")
                    counted = at
            lines.append(printer.statement(statement))
        return lines, counted

    def instruction_lines(self, region, address):
        if address in self.unsupported:
            return [f"z80_fault(\"{self.unsupported[address]}\", {hex16(address)});", f"return {hex16(address)};"]
        lifter = self.lifted[address]
        printer = Printer()
        lines, counted = self.timed(lifter.statements, lifter.accesses, printer, 0)
        control = lifter.control
        following = lifter.next_address
        if control.kind in ("call_if", "return_if"):
            # the taken way: its own accesses after the common ones
            taken, end = self.timed(lifter.taken_statements, lifter.taken_accesses, printer, counted)
            extra = lifter.cycles + lifter.extras["taken"] - end
            if extra:
                taken.append(f"z80.cycles += {extra};")
            where = hex16(control.target) if control.kind == "call_if" else f"(uint16_t)({printer.expr(control.address)})"
            taken += [f"{{ const uint16_t target = {where}; Z80_CHECK(target); return target; }}"]
            lines += [f"if ({printer.expr(control.condition)})", "{"] + [f"\t{line}" for line in taken] + ["}"]
            if lifter.cycles > counted:
                lines.append(f"z80.cycles += {lifter.cycles - counted};")
            lines += [f"Z80_CHECK({hex16(following)});", self.transfer(region, following)]
            return lines
        if lifter.cycles > counted:
            lines.append(f"z80.cycles += {lifter.cycles - counted};")
        if control.kind == "next":
            lines += [f"Z80_CHECK({hex16(following)});", self.transfer(region, following)]
        elif control.kind == "goto":
            lines += [f"Z80_CHECK({hex16(control.target)});", self.transfer(region, control.target)]
        elif control.kind == "branch":
            extra = lifter.extras.get("taken", 0)
            taken = ([f"z80.cycles += {extra};"] if extra else []) + \
                [f"Z80_CHECK({hex16(control.target)});", self.transfer(region, control.target)]
            lines += [f"if ({printer.expr(control.condition)})", "{"] + [f"\t{line}" for line in taken] + ["}"]
            lines += [f"Z80_CHECK({hex16(following)});", self.transfer(region, following)]
        elif control.kind == "call":
            lines += [f"Z80_CHECK({hex16(control.target)});", f"return {hex16(control.target)};"]
        elif control.kind in ("jump", "return"):
            lines += [f"{{ const uint16_t target = (uint16_t)({printer.expr(control.address)});",
                      "Z80_CHECK(target); return target; }"]
        elif control.kind == "halt":
            lines += [f"return z80_halt({hex16(following)});"]
        else:
            raise ValueError(control.kind)
        return lines

    def region_text(self, region):
        body = self.regions[region]
        lines = [f"uint16_t z_{region:04X}(uint16_t pc)", "{", "\tswitch (pc)", "\t{"]
        lines += [f"\tcase {hex16(a)}: goto L_{a:04X};" for a in body]
        lines += ["\tdefault: return z80_not_code(pc);", "\t}"]
        for address in body:
            text = self.instructions[address].text.replace("*/", "* /")
            lines += [f"L_{address:04X}:\t/* {address:04X}  {text} */", "\t{"]
            lines += [f"\t\t{line}" for line in self.instruction_lines(region, address)]
            lines.append("\t}")
        lines.append("}")
        return "\n".join(lines)

    def irq_entry_text(self):
        printer = Printer()
        entry = lift.IrqEntry(0, prefix="t_")
        lines = ["uint16_t z80_irq_entry(uint16_t pc)", "{"]
        data = [a for a in entry.accesses if a.address is None]
        counted, position, stores = 0, 0, 0
        for statement in entry.statements:
            if isinstance(statement, ir.Store):
                at = data[position].cycle
                position += 1
                if at > counted:
                    lines.append(f"\tz80.cycles += {at - counted};")
                    counted = at
                # the PC pushed is the argument: its high byte first
                value = "(uint8_t)(pc >> 8)" if stores == 0 else "(uint8_t)(pc & 0xFFu)"
                stores += 1
                lines.append(f"\tz80_write8({printer.expr(statement.address)}, {value});")
                continue
            lines.append(f"\t{printer.statement(statement)}")
        if entry.cycles > counted:
            lines.append(f"\tz80.cycles += {entry.cycles - counted};")
        lines += ["\treturn 0x0038u;", "}"]
        return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[2])
    parser.add_argument("--rom", nargs="*")
    args = parser.parse_args()
    program = analysis.load(args.rom)
    code = analysis.explore(program)
    translator = Translator(program, code)
    os.makedirs(OUT, exist_ok=True)
    for old in os.listdir(OUT):
        if old.startswith("sound_") and old.endswith(".c"):
            os.remove(os.path.join(OUT, old))
    regions = sorted(translator.regions)
    with open(os.path.join(OUT, "sound_program.h"), "w", encoding="ascii", newline="\n") as out:
        out.write(HEADER + "#ifndef MAKAIMURA_SOUND_PROGRAM_H\n#define MAKAIMURA_SOUND_PROGRAM_H\n\n#include <stdint.h>\n\n"
                  + "\n".join(f"uint16_t z_{r:04X}(uint16_t pc);" for r in regions) + "\n\n#endif\n")
    include = '#include "z80/cpu.h"\n#include "sound_program.h"\n\n'
    files = 0
    for number, first in enumerate(range(0, len(regions), REGIONS_PER_FILE)):
        texts = [translator.region_text(r) for r in regions[first:first + REGIONS_PER_FILE]]
        if number == 0:
            texts.insert(0, translator.irq_entry_text())
        with open(os.path.join(OUT, f"sound_{number:02}.c"), "w", encoding="ascii", newline="\n") as out:
            out.write(HEADER + include + "\n\n".join(texts) + "\n")
        files += 1
    rows = [f"\t{{ {hex16(a)}, z_{translator.owner[a]:04X} }}," for a in sorted(translator.instructions)]
    with open(os.path.join(OUT, "sound_entries.c"), "w", encoding="ascii", newline="\n") as out:
        out.write(HEADER + include + "const z80_entry z80_entries[] =\n{\n" + "\n".join(rows) + "\n};\n"
                  + f"const unsigned z80_entry_count = {len(rows)};\n")
    print(f"instructions:   {len(translator.instructions)} in {len(regions)} regions, {files} files")
    print(f"not translated: {len(translator.unsupported)}")
    for address, problem in sorted(translator.unsupported.items())[:10]:
        print(f"  {address:04X}  {problem}")
    print(f"Output: {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
